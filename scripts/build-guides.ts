/**
 * Guides Build Script
 *
 * Parses the markdown articles in src/content/guides/ into a structured
 * TypeScript module (src/data/guides.generated.ts) that the site renders.
 * Runs automatically via the predev/prebuild scripts, next to the sitemap.
 *
 * Run manually after editing any guide article:
 *   bun scripts/build-guides.ts
 */

import { readdirSync, readFileSync, writeFileSync } from "fs";
import { fileURLToPath } from "url";
import { parseGuide, type ParsedGuide } from "../src/lib/guides-parser";

const CONTENT_DIR = fileURLToPath(new URL("../src/content/guides/", import.meta.url));
const OUTPUT_PATH = fileURLToPath(new URL("../src/data/guides.generated.ts", import.meta.url));

// Sections that exist only as editor placeholders and must not be published.
const STRIP_SECTIONS: Record<string, string[]> = {
  "how-much-does-seo-cost": ["What I charge"],
};

function main() {
  console.log("📚 Building Small Business Guides...");
  const files = readdirSync(CONTENT_DIR)
    .filter((name) => name.endsWith(".md"))
    .sort();

  const guides: ParsedGuide[] = files.map((name) => {
    const slug = name.replace(/\.md$/, "");
    const raw = readFileSync(CONTENT_DIR + name, "utf-8");
    const guide = parseGuide(raw, { slug, stripSections: STRIP_SECTIONS[slug] });
    console.log(`   ✓ ${slug} (${guide.blocks.length} blocks, ${guide.faqs.length} FAQs)`);
    return guide;
  });

  const output = `// AUTO-GENERATED by scripts/build-guides.ts — do not edit by hand.
// Source articles live in src/content/guides/.
import type { ParsedGuide } from "@/lib/guides-parser";

export const parsedGuides: ParsedGuide[] = ${JSON.stringify(guides, null, 2)};
`;

  writeFileSync(OUTPUT_PATH, output, "utf-8");
  console.log(`✅ Generated ${guides.length} guides → ${OUTPUT_PATH}`);
}

main();
